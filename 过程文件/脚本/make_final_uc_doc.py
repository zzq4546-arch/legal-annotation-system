def set_font(run, ascii_font, ea_font, size=None, bold=None, color=None, italic=None):
    run.font.name = ascii_font
    if size:
        run.font.size = size
    if bold is not None:
        run.bold = bold
    if italic is not None:
        run.italic = italic
    if color:
        run.font.color.rgb = color
    rPr = run._element.get_or_add_rPr()
    rf = rPr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts'); rPr.insert(0, rf)
    rf.set(qn('w:ascii'), ascii_font); rf.set(qn('w:hAnsi'), ascii_font)
    rf.set(qn('w:eastAsia'), ea_font); rf.set(qn('w:cs'), ascii_font)


def heading(text, level=1):
    p = doc.add_heading('', level=level)
    p.paragraph_format.space_before = Pt(10 if level > 1 else 0)
    p.paragraph_format.space_after = Pt(5)
    r = p.add_run(text)
    set_font(r, 'Times New Roman', CA, size=HSPEC[level], bold=True, color=RGBColor(0x1F, 0x30, 0x50))
    return p


def para(text, size=10.5, bold=False, indent=0.0, italic=False, color=None, align=None):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(3)
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    if align:
        p.alignment = align
    r = p.add_run(text)
    set_font(r, 'Times New Roman', CB, size=Pt(size), bold=bold, italic=italic, color=color)
    return p


def bullets(items, size=10.5, indent=0.75):
    for it in items:
        p = doc.add_paragraph(style='List Bullet')
        p.paragraph_format.space_after = Pt(1.5)
        p.paragraph_format.left_indent = Cm(indent)
        r = p.add_run(it)
        set_font(r, 'Times New Roman', CB, size=Pt(size))


def set_table_width(t, widths):
    tbl = t._tbl
    tblPr = tbl.tblPr
    for tag in ('w:tblW', 'w:tblLayout'):
        for el in tblPr.findall(qn(tag)):
            tblPr.remove(el)
    el = OxmlElement('w:tblW'); el.set(qn('w:type'), 'dxa')
    el.set(qn('w:w'), str(int(round(sum(widths) * 567)))); tblPr.append(el)
    el = OxmlElement('w:tblLayout'); el.set(qn('w:type'), 'fixed'); tblPr.append(el)
    for grid in tbl.findall(qn('w:tblGrid')):
        tbl.remove(grid)
    grid = OxmlElement('w:tblGrid')
    for w in widths:
        gc = OxmlElement('w:gridCol'); gc.set(qn('w:w'), str(int(round(w * 567)))); grid.append(gc)
    tbl.insert(list(tbl).index(tblPr) + 1, grid)
    for row in t.rows:
        for i, c in enumerate(row.cells):
            c.width = Cm(widths[i])


def grid_table(header, rows, widths, sizes=None):
    sizes = sizes or ([10] * len(header))
    t = doc.add_table(rows=0, cols=len(header))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.LEFT
    t.autofit = False
    if header:
        cells = t.add_row().cells
        for i, h in enumerate(header):
            p = cells[i].paragraphs[0]
            set_font(p.add_run(h), 'Times New Roman', CA, size=Pt(sizes[i]), bold=True)
            p.paragraph_format.space_after = Pt(1)
    for row in rows:
        cells = t.add_row().cells
        for i in range(len(header)):
            v = row[i] if i < len(row) else ''
            p = cells[i].paragraphs[0]
            p.paragraph_format.space_after = Pt(1)
            p.paragraph_format.line_spacing = 1.12
            lines = v if isinstance(v, list) else [v]
            for li, line in enumerate(lines):
                if li:
                    p = cells[i].add_paragraph()
                    p.paragraph_format.space_after = Pt(1)
                set_font(p.add_run(line), 'Times New Roman', CB, size=Pt(sizes[i]))
    set_table_width(t, widths)
    return t


def kv_table(rows, w1=5.0, total=USABLE, key_size=10, val_size=10):
    t = doc.add_table(rows=0, cols=2)
    t.style = 'Table Grid'
    t.autofit = False
    t.alignment = WD_TABLE_ALIGNMENT.LEFT
    for k, v in rows:
        cells = t.add_row().cells
        p0 = cells[0].paragraphs[0]
        p0.paragraph_format.space_after = Pt(1)
        set_font(p0.add_run(k), 'Times New Roman', CA, size=Pt(key_size), bold=True)
        lines = v if isinstance(v, list) else [v]
        p1 = cells[1].paragraphs[0]
        for li, line in enumerate(lines):
            if li:
                p1 = cells[1].add_paragraph()
            p1.paragraph_format.space_after = Pt(1)
            p1.paragraph_format.line_spacing = 1.15
            set_font(p1.add_run(line), 'Times New Roman', CB, size=Pt(val_size))
    set_table_width(t, [w1, total - w1])
    return t


