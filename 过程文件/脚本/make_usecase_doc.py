def set_table_width(t, widths):
    tbl = t._tbl
    tblPr = tbl.tblPr
    for tag in ('w:tblW', 'w:tblLayout'):
        for el in tblPr.findall(qn(tag)):
            tblPr.remove(el)
    tblW = OxmlElement('w:tblW')
    tblW.set(qn('w:type'), 'dxa')
    tblW.set(qn('w:w'), str(int(round(sum(widths) * 567))))
    tblPr.append(tblW)
    lay = OxmlElement('w:tblLayout')
    lay.set(qn('w:type'), 'fixed')
    tblPr.append(lay)
    for grid in tbl.findall(qn('w:tblGrid')):
        tbl.remove(grid)
    grid = OxmlElement('w:tblGrid')
    for w in widths:
        gc = OxmlElement('w:gridCol')
        gc.set(qn('w:w'), str(int(round(w * 567))))
        grid.append(gc)
    tbl.insert(list(tbl).index(tblPr) + 1, grid)
    for row in t.rows:
        for i, c in enumerate(row.cells):
            c.width = Cm(widths[i])


def kv_table(rows, w1=4.6, total=USABLE, header=None):
    """Two-column description table; bold left column."""
    t = doc.add_table(rows=0, cols=2)
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.LEFT
    t.autofit = False
    if header:
        cells = t.add_row().cells
        for i, h in enumerate(header[:2]):
            p = cells[i].paragraphs[0]
            r = p.add_run(h)
            set_font(r, 'Times New Roman', CA, size=Pt(10.5), bold=True)
    for k, v in rows:
        cells = t.add_row().cells
        p0 = cells[0].paragraphs[0]
        r0 = p0.add_run(k)
        set_font(r0, 'Times New Roman', CA, size=Pt(10), bold=True)
        p1 = cells[1].paragraphs[0]
        lines = v if isinstance(v, list) else [v]
        for li, line in enumerate(lines):
            if li:
                p1 = cells[1].add_paragraph()
            r1 = p1.add_run(line)
            set_font(r1, 'Times New Roman', CB, size=Pt(10))
        for p in (p0, p1):
            p.paragraph_format.space_after = Pt(1)
            p.paragraph_format.line_spacing = 1.15
    set_table_width(t, [w1, total - w1])
    return t


