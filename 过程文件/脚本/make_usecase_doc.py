def set_font(run, ascii_font, ea_font, size=None, bold=None, color=None):
    run.font.name = ascii_font
    if size:
        run.font.size = size
    if bold is not None:
        run.bold = bold
    if color:
        run.font.color.rgb = color
    rPr = run._element.get_or_add_rPr()
    rf = rPr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts')
        rPr.insert(0, rf)
    rf.set(qn('w:ascii'), ascii_font)
    rf.set(qn('w:hAnsi'), ascii_font)
    rf.set(qn('w:eastAsia'), ea_font)
    rf.set(qn('w:cs'), ascii_font)


def heading(text, level=1):
    p = doc.add_heading('', level=level)
    p.paragraph_format.space_before = Pt(10 if level > 1 else 0)
    p.paragraph_format.space_after = Pt(5)
    r = p.add_run(text)
    set_font(r, 'Times New Roman', CA, size=HSPEC[level], bold=True,
             color=RGBColor(0x1F, 0x30, 0x50))
    return p


def para(text, bold=False, size=10.5, indent=0.0, color=None):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(3)
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    r = p.add_run(text)
    set_font(r, 'Times New Roman', CB, size=Pt(size), bold=bold, color=color)
    return p


